#!/usr/bin/env bash
# Usage: scripts/package-arch.sh <package.deb> [out-dir]
#
# Turns the built (and fix-deb'ed) .deb into an Arch package, zapper-<pkgver>-1-x86_64.pkg.tar.zst,
# without makepkg (the build machine is Ubuntu). out-dir defaults to
# target/release/bundle/arch.
#   payload  = the .deb's data member: same paths and modes, with /usr/lib/zapper/install-kind
#              saying `arch` (packaging/install-kind-arch), plus usr/share/licenses/zapper ->
#              ../doc/zapper (the license notices, where Arch looks for them)
#   .PKGINFO = pacman's key = value metadata; depends mapped from the .deb's Depends through the
#              table in scripts/arch-pkg.py (an unknown Debian name fails the build; a library
#              the payload bundles is dropped); license = MIT and the licenses the third-party
#              notices summarise
#   .MTREE   = gzip'd mtree of .PKGINFO, .INSTALL and the payload, as makepkg's bsdtar writes it
#   .INSTALL = pre_remove: the .deb's prerm on a removal (packaging/linux/deb-prerm), which pacman
#              runs on a removal only, not an upgrade
# Archive order: .PKGINFO, .MTREE, .INSTALL, then the payload; GNU tar, every entry root:root with one fixed
# mtime ($SOURCE_DATE_EPOCH, else the .deb's), zstd -19.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$here")
helper="$here/arch-pkg.py"
deb=$(realpath "${1:?usage: package-arch.sh <package.deb> [out-dir]}")
out=${2:-target/release/bundle/arch}
fail() { echo "package-arch: $*" >&2; exit 1; }
[ -f "$deb" ] || fail "no such file: $deb"
for tool in ar dpkg-deb python3 zstd; do
  command -v "$tool" >/dev/null || fail "needs $tool"
done
mkdir -p "$out"
out=$(realpath "$out")

name=$(dpkg-deb -f "$deb" Package)
[ "$name" = zapper ] || fail "the .deb's package is $name, not zapper"
debver=$(dpkg-deb -f "$deb" Version)
pkgver=$(python3 "$helper" pkgver "$debver")-1
epoch=${SOURCE_DATE_EPOCH:-$(stat -c %Y "$deb")}
pkgdesc=$(dpkg-deb -f "$deb" Description | head -1)
url="https://github.com/$("$here/releases-repo.sh")"

# The work dir sits next to the output, not in /tmp (often tmpfs).
work=$(mktemp -d "$out/.work.XXXXXX"); trap 'rm -rf "$work"' EXIT
(cd "$work" && ar x "$deb")
[ -f "$work/debian-binary" ] || fail "not a .deb: $deb"
data=$(cd "$work" && ls data.tar.*)
case "$data" in
  *.gz) unpack=(gzip -dc) ;;
  *.xz) unpack=(xz -dc) ;;
  *.zst) unpack=(zstd -dcq) ;;
  *.tar) unpack=(cat) ;;
  *) fail "unknown data member compression: $data" ;;
esac
"${unpack[@]}" "$work/$data" > "$work/data.tar"
rm "$work/$data"
mkdir "$work/pkg"
# -p keeps the recorded modes; a normal user can't chown, so ownership is set in the archive below.
tar -xpf "$work/data.tar" -C "$work/pkg" --no-same-owner
[ -e "$work/pkg/.PKGINFO" ] && fail "the .deb's payload has a .PKGINFO"
[ -x "$work/pkg/usr/bin/zapper" ] || fail "the .deb has no usr/bin/zapper"

# Dependencies: after unpacking, so a library the payload carries is left out of them.
mapfile -t depends < <(python3 "$helper" depends "$(dpkg-deb -f "$deb" Depends)" "$work/pkg")
[ ${#depends[@]} -gt 0 ] || fail "no dependencies mapped"

# The license notices (docs/licensing.md) are in the .deb's /usr/share/doc/zapper/. Arch looks
# for license files in /usr/share/licenses/<pkg>/, so that is a symlink to the same directory.
for f in LICENSE MPV-FFMPEG-NOTICE.txt THIRD-PARTY-NOTICES-rust.txt THIRD-PARTY-NOTICES-ui.txt; do
  [ -s "$work/pkg/usr/share/doc/zapper/$f" ] || fail "the .deb has no usr/share/doc/zapper/$f (or it's empty)"
done
[ -e "$work/pkg/usr/share/licenses/zapper" ] && fail "the .deb's payload already has usr/share/licenses/zapper"
mkdir -p "$work/pkg/usr/share/licenses"
chmod 755 "$work/pkg/usr/share/licenses"
ln -s ../doc/zapper "$work/pkg/usr/share/licenses/zapper"
mapfile -t licenses < <(python3 "$helper" licenses "$work/pkg/usr/share/doc/zapper")
[ ${#licenses[@]} -gt 0 ] || fail "no licenses found"

# How the package was installed (the updater picks the Arch package and pacman by it): `arch`,
# where the .deb says `deb`.
kind=usr/lib/zapper/install-kind
[ "$(cat "$work/pkg/$kind" 2>/dev/null)" = deb ] || fail "the .deb has no $kind saying deb"
# Written over, not replaced, so the file keeps the .deb's mode.
cat "$root/packaging/install-kind-arch" > "$work/pkg/$kind"
edited=("$kind")

size=$(python3 "$helper" size "$work/pkg")
{
  echo "# Generated by scripts/package-arch.sh from $(basename "$deb")"
  echo "pkgname = zapper"
  echo "pkgbase = zapper"
  echo "xdata = pkgtype=pkg"
  echo "pkgver = $pkgver"
  echo "pkgdesc = $pkgdesc"
  echo "url = $url"
  echo "builddate = $epoch"
  echo "packager = zapper build"
  echo "size = $size"
  echo "arch = x86_64"
  printf 'license = %s\n' "${licenses[@]}"
  printf 'depend = %s\n' "${depends[@]}"
} > "$work/pkg/.PKGINFO"
chmod 644 "$work/pkg/.PKGINFO"
# The same stop as the .deb's prerm, run by pacman before a removal (never an upgrade, which is
# pre_upgrade). Taken from the prerm itself so the two cannot drift.
{
  echo "# Generated by scripts/package-arch.sh from packaging/linux/deb-prerm"
  echo "pre_remove() {"
  echo "  sh -s remove <<'PRERM'"
  cat "$root/packaging/linux/deb-prerm"
  echo "PRERM"
  echo "}"
} > "$work/pkg/.INSTALL"
chmod 644 "$work/pkg/.INSTALL"
python3 "$helper" mtree "$work/pkg" "$epoch" "$work/pkg/.MTREE"
chmod 644 "$work/pkg/.MTREE"

file="zapper-$pkgver-x86_64.pkg.tar.zst"
mapfile -t payload < <(cd "$work/pkg" && find . -mindepth 1 -maxdepth 1 ! -name '.*' -printf '%P\n' | LC_ALL=C sort)
tar -C "$work/pkg" --format=gnu --sort=name --mtime="@$epoch" \
    --owner=root:0 --group=root:0 --no-recursion -cf "$work/pkg.tar" .PKGINFO .MTREE .INSTALL
tar -C "$work/pkg" --format=gnu --sort=name --mtime="@$epoch" \
    --owner=root:0 --group=root:0 -rf "$work/pkg.tar" "${payload[@]}"

# The payload must match the .deb entry for entry (plus the licenses symlink), all root-owned.
python3 "$helper" verify "$work/data.tar" "$work/pkg.tar" "${edited[@]}" >/dev/null
[ "$(tar -tf "$work/pkg.tar" | head -2 | tr '\n' ' ')" = ".PKGINFO .MTREE " ] || fail "the archive doesn't start with .PKGINFO, .MTREE"
[ "$(tar -xOf "$work/pkg.tar" "$kind")" = arch ] || fail "the package's install-kind isn't arch"

rm -f "$out"/zapper-*-x86_64.pkg.tar.zst
zstd -19 -T0 -q --rm "$work/pkg.tar" -o "$out/$file"
echo "package-arch: $out/$file ($(du -h "$out/$file" | cut -f1)); pkgver $pkgver; depends: ${depends[*]}"
